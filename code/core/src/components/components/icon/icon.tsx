import styles from './icon.module.css';

export type IconType = keyof typeof icons;

export interface IconsProps extends ComponentProps<'svg'> {
  /** An icon name from the `icons` map. An unknown name logs a warning and shows nothing. */
  icon: string;
  useSymbol?: boolean;
  onClick?: () => void;
  __suppressDeprecationWarning?: boolean;
}

// TODO: Remove in SB11
/**
 * @deprecated Import an icon from `lucide-react` instead. This component maps the old
 *   Storybook icon names to Lucide icons.
 */
export const Icons = ({
  icon,
  useSymbol,
  __suppressDeprecationWarning = false,
  ...props
}: IconsProps) => {
  if (!__suppressDeprecationWarning) {
    deprecate(
      `Use of the deprecated Icons ${
        `(${icon})` || ''
      } component detected. Import an icon from lucide-react instead. For more informations, see the migration notes at https://forkbook.ljk.dev/docs/migration#icons-is-deprecated`
    );
  }

  const Icon = icons[icon as IconType];
  if (!Icon) {
    logger.warn(
      `Use of an unknown prop ${
        `(${icon})` || ''
      } in the Icons component. The Icons component is deprecated. Import an icon from lucide-react instead. For more informations, see the migration notes at https://forkbook.ljk.dev/docs/migration#icons-is-deprecated`
    );
    return null;
  }

  return <Icon size={14} {...props} />;
};

export interface SymbolsProps {
  icons?: IconType[];
}

// TODO: Remove in SB11
/**
 * @deprecated Import an icon from `lucide-react` instead. This component maps the old
 *   Storybook icon names to Lucide icons.
 */
export const Symbols = memo<SymbolsProps>(function Symbols({
  icons: keys = Object.keys(icons) as IconType[],
}) {
  return (
    <svg
      className={styles.svg}
      viewBox="0 0 14 14"
      style={{ position: 'absolute', width: 0, height: 0 }}
      data-chromatic="ignore"
    >
      {keys.map((key) => {
        const Icon = icons[key];
        return (
          <symbol id={`icon--${key}`} key={key}>
            <Icon size={14} />
          </symbol>
        );
      })}
    </svg>
  );
});

