/**
 * The virtual preview route of builder-next. Next.js finds routes only in the `app` folder on disk
 * (`next/dist/lib/find-pages-dir.js`), and no config key or plugin hook adds a route from another
 * place. So Forkbook writes a small route group, `<app>/(forkbook)`, when `next dev` starts and
 * removes it when `next dev` stops. Git ignores it through `.git/info/exclude`, which is not a
 * committed file. See `docs/plans/builder-next-spike.md`.
 *
 * This module uses only Node built-ins, so `@aussieljk/forkbook/next` can import it.
 */
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path';

/** The route group that holds the generated files. The parentheses keep it out of the URL. */
export const PREVIEW_ROUTE_GROUP = '(forkbook)';

/** The last URL segment of the preview route: `<base>/iframe`. */
export const PREVIEW_ROUTE_SEGMENT = 'iframe';

/** The path (under the base path) of the preview globals that the Forkbook server serves. */
export const PREVIEW_GLOBALS_PATH = '/iframe-globals.json';

/** The names of the generated files in the route folder. */
export const PREVIEW_ROUTE_FILES = {
  page: 'page.tsx',
  client: 'forkbook-client.tsx',
  runtime: 'forkbook-runtime.tsx',
  stories: 'forkbook-stories.js',
  annotations: 'forkbook-annotations.js',
} as const;

const GENERATED_HEADER =
  '// Generated by Forkbook (builder-next). Do not edit. It is removed when `next dev` stops.\n';

/** Gives `<project>/app` or `<project>/src/app`, the same order as Next.js. */
export function findAppDir(projectDir: string): string | undefined {
  for (const candidate of [join(projectDir, 'app'), join(projectDir, 'src', 'app')]) {
    if (existsSync(candidate)) {
      return candidate;
    }
  }
  return undefined;
}

/**
 * Turns a base path into app router folder names. A folder that starts with `_` is a private
 * folder in the app router, so a leading `_` is written as `%5F`.
 */
export function getRouteSegments(basePath: string): string[] {
  return basePath
    .split('/')
    .filter(Boolean)
    .map((segment) => (segment.startsWith('_') ? `%5F${segment.slice(1)}` : segment));
}

/** The route group folder: `<app>/(forkbook)`. */
export function getRouteGroupDir(appDir: string): string {
  return join(appDir, PREVIEW_ROUTE_GROUP);
}

/** The folder of the preview page: `<app>/(forkbook)/%5Fforkbook/iframe`. */
export function getPreviewRouteDir(appDir: string, basePath: string): string {
  return join(getRouteGroupDir(appDir), ...getRouteSegments(basePath), PREVIEW_ROUTE_SEGMENT);
}

/** A module specifier for `target`, relative to `fromDir`, with `/` and a leading `./`. */
export function toImportSpecifier(fromDir: string, target: string): string {
  if (!isAbsolute(target)) {
    return target;
  }
  const path = relative(fromDir, target).split(sep).join('/');
  return path.startsWith('.') ? path : `./${path}`;
}

/** The part of a story index entry that the loader needs. */
export interface StoryLoaderEntry {
  importPath: string;
}

export interface StoryLoaderOptions {
  /** The folder the index import paths are relative to (the Forkbook working folder). */
  workingDir: string;
  /** The folder of the generated module. Imports are relative to it. */
  routeDir: string;
}

/** The unique import paths of a story index, sorted, so the module text is stable. */
export function getStoryImportPaths(entries: Record<string, StoryLoaderEntry>): string[] {
  return [...new Set(Object.values(entries).map((entry) => entry.importPath))].sort();
}

/**
 * Makes the story loader module. It maps each import path of the index to a lazy `import()`, so
 * Next.js splits each story file into its own chunk and loads it when the story is shown.
 */
export function generateStoryLoaderCode(
  entries: Record<string, StoryLoaderEntry>,
  { workingDir, routeDir }: StoryLoaderOptions
): string {
  const lines = getStoryImportPaths(entries).map((importPath) => {
    const specifier = importPath.startsWith('virtual:')
      ? importPath
      : toImportSpecifier(routeDir, resolve(workingDir, importPath));
    return `  ${JSON.stringify(importPath)}: () => import(${JSON.stringify(specifier)}),`;
  });
  return `${GENERATED_HEADER}
const importers = {
${lines.join('\n')}
};

export async function importFn(path) {
  const importer = importers[path];
  if (!importer) {
    throw new Error(\`Forkbook: no story file for "\${path}". Restart next dev if it is new.\`);
  }
  return importer();
}
`;
}

/**
 * Makes the project annotations module from the preview annotation files (addons, renderer,
 * framework, then `.forkbook/preview`). The last file is the project preview. A CSF factory
 * preview (`definePreview`) gives `default.composed`, which is used as it is.
 */
export function generateAnnotationsCode(annotationPaths: string[], routeDir: string): string {
  const specifiers = annotationPaths.map((path) => toImportSpecifier(routeDir, path));
  const imports = specifiers.map(
    (specifier, index) => `import * as annotations${index} from ${JSON.stringify(specifier)};`
  );
  const names = specifiers.map((_, index) => `annotations${index}`);
  return `${GENERATED_HEADER}
import { composeConfigs } from '@aussieljk/forkbook/preview-api';
${imports.join('\n')}

const modules = [${names.join(', ')}];

export function getProjectAnnotations() {
  const preview = modules[modules.length - 1];
  if (preview?.default?.composed) {
    return preview.default.composed;
  }
  return composeConfigs(modules);
}
`;
}

/** The server component page. It only renders the client component. */
export function generatePageCode(): string {
  return `${GENERATED_HEADER}
import ForkbookClient from './${PREVIEW_ROUTE_FILES.client.replace(/\.tsx$/, '')}';

export const metadata = { title: 'Forkbook', robots: { index: false, follow: false } };

export default function ForkbookPreviewPage() {
  return <ForkbookClient />;
}
`;
}

/**
 * The client component. It loads the preview runtime only in the browser (`ssr: false`), because
 * the preview runtime and many story files read `window` when they load.
 */
export function generateClientCode(): string {
  return `${GENERATED_HEADER}
'use client';

import dynamic from 'next/dynamic';

const ForkbookRuntime = dynamic(() => import('./${PREVIEW_ROUTE_FILES.runtime.replace(/\.tsx$/, '')}'), {
  ssr: false,
});

export default function ForkbookClient() {
  return <ForkbookRuntime />;
}
`;
}

export interface RuntimeCodeOptions {
  basePath: string;
}

/**
 * The browser module that starts the preview, the same as `vite-app.js` of builder-vite. Next.js
 * runs this module again on a hot update of a story file or of the loader module (it is a React
 * Refresh boundary). The second run gives the new `importFn` to the running preview.
 */
export function generateRuntimeCode({ basePath }: RuntimeCodeOptions): string {
  const globalsUrl = `${basePath}${PREVIEW_GLOBALS_PATH}`;
  return `${GENERATED_HEADER}
'use client';

import { useEffect } from 'react';
import { setup } from '@aussieljk/forkbook/internal/preview/runtime';
import { createBrowserChannel } from '@aussieljk/forkbook/internal/channels';
import { addons, PreviewWeb } from '@aussieljk/forkbook/preview-api';
import { importFn } from './${PREVIEW_ROUTE_FILES.stories}';
import { getProjectAnnotations } from './${PREVIEW_ROUTE_FILES.annotations}';

const w = window;

async function loadGlobals() {
  const response = await fetch(${JSON.stringify(globalsUrl)});
  if (!response.ok) {
    throw new Error('Forkbook: could not load the preview globals (' + response.status + ').');
  }
  Object.assign(w, await response.json());
  w.global = w;
  w.module = undefined;
}

async function start() {
  if (!w.__FORKBOOK_PREVIEW_STARTING__) {
    w.__FORKBOOK_PREVIEW_STARTING__ = (async () => {
      await loadGlobals();
      setup();
      const channel = createBrowserChannel({ page: 'preview' });
      addons.setChannel(channel);
      if (w.CONFIG_TYPE === 'DEVELOPMENT') {
        w.__FORKBOOK_SERVER_CHANNEL__ = channel;
      }
      w.__FORKBOOK_PREVIEW__ = new PreviewWeb(importFn, getProjectAnnotations);
      w.__FORKBOOK_STORY_STORE__ = w.__FORKBOOK_PREVIEW__.storyStore;
    })();
    return w.__FORKBOOK_PREVIEW_STARTING__;
  }
  // A hot update ran this module again. Give the new modules to the running preview.
  await w.__FORKBOOK_PREVIEW_STARTING__;
  const preview = w.__FORKBOOK_PREVIEW__;
  await preview.onGetProjectAnnotationsChanged({ getProjectAnnotations });
  await preview.onStoriesChanged({ importFn });
  w.__FORKBOOK_SERVER_CHANNEL__?.emit('storyHotUpdated');
}

const started = start().catch((error) => {
  console.error(error);
});

export default function ForkbookRuntime() {
  useEffect(() => {
    void started;
  }, []);
  return (
    <>
      <div id="storybook-root" />
      <div id="storybook-docs" />
    </>
  );
}
`;
}

/** Writes a file only when its text changed, so Next.js does not see a change with no effect. */
export function writeIfChanged(path: string, content: string): boolean {
  if (existsSync(path) && readFileSync(path, 'utf8') === content) {
    return false;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  return true;
}

export interface PreviewRouteOptions {
  /** The Next.js project folder (where `next.config` is). */
  projectDir: string;
  /** The normalised base path, for example `/_forkbook`. */
  basePath: string;
  /** The app folder. Default: `<projectDir>/app` or `<projectDir>/src/app`. */
  appDir?: string;
}

export interface PreviewRoute {
  appDir: string;
  /** `<app>/(forkbook)`: remove this folder to remove the route. */
  groupDir: string;
  /** The folder of the page and the generated modules. */
  routeDir: string;
}

/** Gives the folders of the preview route. Throws when the project has no `app` folder. */
export function resolvePreviewRoute({
  projectDir,
  basePath,
  appDir,
}: PreviewRouteOptions): PreviewRoute {
  const app = appDir ?? findAppDir(projectDir);
  if (!app) {
    throw new Error(
      `Forkbook (builder-next): no "app" or "src/app" folder in ${projectDir}. builder-next needs the App Router.`
    );
  }
  return {
    appDir: app,
    groupDir: getRouteGroupDir(app),
    routeDir: getPreviewRouteDir(app, basePath),
  };
}

/**
 * Writes the static files of the preview route (page, client component, runtime) and empty
 * loader modules when they do not exist yet. The Forkbook server writes the real loader modules
 * when the story index is ready.
 */
export function writePreviewRoute(options: PreviewRouteOptions): PreviewRoute {
  const route = resolvePreviewRoute(options);
  const { routeDir } = route;
  writeIfChanged(join(routeDir, PREVIEW_ROUTE_FILES.page), generatePageCode());
  writeIfChanged(join(routeDir, PREVIEW_ROUTE_FILES.client), generateClientCode());
  writeIfChanged(
    join(routeDir, PREVIEW_ROUTE_FILES.runtime),
    generateRuntimeCode({ basePath: options.basePath })
  );
  const stories = join(routeDir, PREVIEW_ROUTE_FILES.stories);
  if (!existsSync(stories)) {
    writeIfChanged(stories, generateStoryLoaderCode({}, { workingDir: routeDir, routeDir }));
  }
  const annotations = join(routeDir, PREVIEW_ROUTE_FILES.annotations);
  if (!existsSync(annotations)) {
    writeIfChanged(annotations, generateAnnotationsCode([], routeDir));
  }
  ignoreInGit(route.groupDir);
  return route;
}

/** Removes `<app>/(forkbook)`. */
export function removePreviewRoute(route: Pick<PreviewRoute, 'groupDir'>): void {
  rmSync(route.groupDir, { recursive: true, force: true });
}

/** Finds the `.git` folder above `dir`. A worktree or submodule `.git` file is followed. */
export function findGitDir(dir: string): string | undefined {
  let current = resolve(dir);
  while (true) {
    const candidate = join(current, '.git');
    if (existsSync(candidate)) {
      try {
        const text = readFileSync(candidate, 'utf8');
        const match = /^gitdir:\s*(.+)$/m.exec(text);
        if (match) {
          const gitDir = resolve(current, match[1].trim());
          // A worktree keeps `info/exclude` in the common folder.
          const common = join(gitDir, 'commondir');
          return existsSync(common) ? resolve(gitDir, readFileSync(common, 'utf8').trim()) : gitDir;
        }
      } catch {
        // `.git` is a folder: readFileSync fails with EISDIR.
      }
      return candidate;
    }
    const parent = dirname(current);
    if (parent === current) {
      return undefined;
    }
    current = parent;
  }
}

/**
 * Adds the route group to `.git/info/exclude`, so `git status` does not show it. This file is
 * local to the clone and is never committed. Returns false when there is no Git repository.
 */
export function ignoreInGit(groupDir: string): boolean {
  const gitDir = findGitDir(dirname(groupDir));
  if (!gitDir) {
    return false;
  }
  // No leading slash: the pattern matches a `(forkbook)` folder at any depth, in every worktree.
  const pattern = `${PREVIEW_ROUTE_GROUP}/`;
  const excludePath = join(gitDir, 'info', 'exclude');
  const existing = existsSync(excludePath) ? readFileSync(excludePath, 'utf8') : '';
  if (existing.split(/\r?\n/).includes(pattern)) {
    return true;
  }
  mkdirSync(dirname(excludePath), { recursive: true });
  const prefix = existing && !existing.endsWith('\n') ? '\n' : '';
  writeFileSync(
    excludePath,
    `${existing}${prefix}# Forkbook builder-next preview route (generated)\n${pattern}\n`
  );
  return true;
}

/** The part of a Next.js config that `applyPreviewRouteMocks` changes. */
export interface TurbopackConfigLike {
  turbopack?: { resolveAlias?: Record<string, unknown>; [key: string]: unknown };
  [key: string]: unknown;
}

/**
 * A `turbopack.resolveAlias` value: a module, or modules for each condition. Use
 * `{ browser: '…' }` to change only the browser graph, so the server code of the app keeps the
 * real module (for example `node:fs`).
 */
export type PreviewAlias = string | Record<string, string>;

export interface PreviewRouteMocks {
  resolveAlias?: Record<string, PreviewAlias>;
}

/**
 * Turbopack did not apply alias targets with an absolute path in the spike (Next.js 16.4.5). A
 * path relative to the Next.js project folder works, so absolute paths are made relative.
 */
export function toProjectRelativeAlias(alias: PreviewAlias, projectDir: string): PreviewAlias {
  if (typeof alias === 'string') {
    return isAbsolute(alias) ? toImportSpecifier(projectDir, alias) : alias;
  }
  return Object.fromEntries(
    Object.entries(alias).map(([condition, target]) => [
      condition,
      toProjectRelativeAlias(target, projectDir) as string,
    ])
  );
}

/**
 * The seam for `next/*` mocks done with module aliases (phase 3, approach A). It adds the aliases
 * to `turbopack.resolveAlias`. Aliases of the app win over Forkbook aliases. The input is not
 * changed.
 */
export function applyPreviewRouteMocks<T extends TurbopackConfigLike>(
  config: T,
  { resolveAlias = {} }: PreviewRouteMocks,
  projectDir: string = process.cwd()
): T {
  if (Object.keys(resolveAlias).length === 0) {
    return config;
  }
  const aliases = Object.fromEntries(
    Object.entries(resolveAlias).map(([name, alias]) => [
      name,
      toProjectRelativeAlias(alias, projectDir),
    ])
  );
  return {
    ...config,
    turbopack: {
      ...config.turbopack,
      resolveAlias: { ...aliases, ...config.turbopack?.resolveAlias },
    },
  };
}
